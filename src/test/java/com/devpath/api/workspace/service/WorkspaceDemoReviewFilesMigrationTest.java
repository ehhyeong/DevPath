package com.devpath.api.workspace.service;

import static org.assertj.core.api.Assertions.assertThat;

import com.fasterxml.jackson.databind.ObjectMapper;
import java.nio.charset.StandardCharsets;
import java.sql.DriverManager;
import java.util.List;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.springframework.core.io.ClassPathResource;
import org.springframework.core.io.support.EncodedResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

class WorkspaceDemoReviewFilesMigrationTest {
  @ParameterizedTest
  @ValueSource(strings = {"postgresql", "oracle"})
  void fillsOnlyOwnedLiveDemoPrsAndPreservesFilesCommentsStatusAndReview(String vendor)
      throws Exception {
    try (var connection = DriverManager.getConnection("jdbc:h2:mem:demo_review_files_" + vendor)) {
      var jdbc = new JdbcTemplate(new SingleConnectionDataSource(connection, true));
      String booleanType = vendor.equals("oracle") ? "INTEGER" : "BOOLEAN";
      String active = vendor.equals("oracle") ? "0" : "FALSE";
      String deleted = vendor.equals("oracle") ? "1" : "TRUE";
      jdbc.execute("CREATE TABLE users (user_id BIGINT PRIMARY KEY, email VARCHAR(200))");
      jdbc.execute(
          "CREATE TABLE workspace (id BIGINT PRIMARY KEY, owner_id BIGINT, is_deleted "
              + booleanType
              + ")");
      jdbc.execute(
          "CREATE TABLE workspace_code_reviews (id BIGINT PRIMARY KEY, workspace_id BIGINT, external_provider VARCHAR(30), external_id VARCHAR(220), is_deleted "
              + booleanType
              + ", additions INTEGER, deletions INTEGER, status VARCHAR(20), title VARCHAR(200), ai_code_review_id BIGINT)");
      jdbc.execute(
          "CREATE TABLE workspace_code_review_files (id BIGINT GENERATED BY DEFAULT AS IDENTITY, review_id BIGINT, workspace_id BIGINT, file_path VARCHAR(500), diff_text CLOB, additions INTEGER, deletions INTEGER, change_type VARCHAR(30), display_order INTEGER, created_at TIMESTAMP, updated_at TIMESTAMP)");
      jdbc.execute(
          "CREATE TABLE workspace_code_review_comments (review_id BIGINT, body VARCHAR(200))");
      jdbc.execute(
          "INSERT INTO users VALUES (1,'kim.hakseup@devpath.com'),(2,'other@devpath.com')");
      jdbc.execute(
          "INSERT INTO workspace VALUES (1,1,"
              + active
              + "),(2,2,"
              + active
              + "),(3,1,"
              + deleted
              + "),(4,1,"
              + active
              + ")");
      var mapper = new ObjectMapper();
      var presets = List.of("routinecare", "studymate", "pantryshare", "sprintdesk");
      for (int index = 0; index < presets.size(); index++) {
        var fixture =
            mapper.readTree(
                new ClassPathResource("demo/workspace/" + presets.get(index) + "-review.json")
                    .getInputStream());
        jdbc.update(
            "INSERT INTO workspace_code_reviews VALUES (?,1,'DEMO',?,"
                + active
                + ",1000,1000,'OPEN','사용자 PR 제목',77)",
            101 + index,
            fixture.path("key").asText());
        jdbc.update(
            "INSERT INTO workspace_code_review_files (review_id,workspace_id,file_path,diff_text,additions,deletions,display_order) VALUES (?,1,?,'원본 서비스 코드',1,0,0)",
            101 + index,
            fixture.path("filePath").asText());
      }
      String key = "routinecare-records-v1#1";
      jdbc.update(
          "INSERT INTO workspace_code_reviews VALUES (105,1,'GITHUB',?,"
              + active
              + ",1000,1000,'OPEN','외부 PR',78)",
          key);
      jdbc.update(
          "INSERT INTO workspace_code_reviews VALUES (106,1,'DEMO',?,"
              + deleted
              + ",1000,1000,'OPEN','삭제 PR',79)",
          key);
      jdbc.update(
          "INSERT INTO workspace_code_reviews VALUES (107,2,'DEMO',?,"
              + active
              + ",1000,1000,'OPEN','다른 소유자',80)",
          key);
      jdbc.update(
          "INSERT INTO workspace_code_reviews VALUES (108,1,'DEMO','manual-key',"
              + active
              + ",1000,1000,'OPEN','알 수 없는 시드',81)");
      jdbc.update(
          "INSERT INTO workspace_code_reviews VALUES (109,3,'DEMO',?,"
              + active
              + ",1000,1000,'OPEN','삭제 워크스페이스',82)",
          key);
      jdbc.update(
          "INSERT INTO workspace_code_reviews VALUES (110,4,'DEMO',?,"
              + active
              + ",1000,1000,'MERGED','이미 병합한 PR',83)",
          key);
      jdbc.update(
          "INSERT INTO workspace_code_review_files (review_id,workspace_id,file_path,diff_text,additions,deletions,display_order) VALUES (110,4,'src/main/java/com/routinecare/record/DailyRecordService.java','기존 코드',1,0,0)");
      jdbc.update(
          "INSERT INTO workspace_code_review_files (review_id,workspace_id,file_path,diff_text,additions,deletions,display_order) VALUES (101,1,'src/main/java/com/routinecare/record/DailyRecordController.java','직접 수정한 코드',99,1,17),(101,1,'notes/custom.ts','사용자 추가 파일',3,2,18)");
      jdbc.update("INSERT INTO workspace_code_review_comments VALUES (101,'기존 팀원 댓글')");
      var script =
          new EncodedResource(
              new ClassPathResource("db/migration/" + vendor + "/V7__expand_demo_review_files.sql"),
              StandardCharsets.UTF_8);
      ScriptUtils.executeSqlScript(connection, script);
      int firstCount =
          jdbc.queryForObject("SELECT count(*) FROM workspace_code_review_files", Integer.class);
      ScriptUtils.executeSqlScript(connection, script);
      assertThat(
              jdbc.queryForObject(
                  "SELECT count(*) FROM workspace_code_review_files", Integer.class))
          .isEqualTo(firstCount);
      assertThat(
              jdbc.queryForObject(
                  "SELECT count(*) FROM workspace_code_review_files WHERE review_id=101",
                  Integer.class))
          .isEqualTo(6);
      for (int reviewId : List.of(102, 103, 104, 110))
        assertThat(
                jdbc.queryForObject(
                    "SELECT count(*) FROM workspace_code_review_files WHERE review_id=?",
                    Integer.class,
                    reviewId))
            .isEqualTo(5);
      for (int reviewId : List.of(105, 106, 107, 108, 109)) {
        assertThat(
                jdbc.queryForObject(
                    "SELECT count(*) FROM workspace_code_review_files WHERE review_id=?",
                    Integer.class,
                    reviewId))
            .isZero();
        assertThat(
                jdbc.queryForObject(
                    "SELECT additions FROM workspace_code_reviews WHERE id=?",
                    Integer.class,
                    reviewId))
            .isEqualTo(1000);
      }
      assertThat(
              jdbc.queryForObject(
                  "SELECT diff_text FROM workspace_code_review_files WHERE review_id=101 AND file_path LIKE '%Controller.java'",
                  String.class))
          .isEqualTo("직접 수정한 코드");
      assertThat(
              jdbc.queryForObject(
                  "SELECT body FROM workspace_code_review_comments WHERE review_id=101",
                  String.class))
          .isEqualTo("기존 팀원 댓글");
      assertThat(
              jdbc.queryForObject(
                  "SELECT title FROM workspace_code_reviews WHERE id=101", String.class))
          .isEqualTo("사용자 PR 제목");
      assertThat(
              jdbc.queryForObject(
                  "SELECT status FROM workspace_code_reviews WHERE id=110", String.class))
          .isEqualTo("MERGED");
      assertThat(
              jdbc.queryForObject(
                  "SELECT ai_code_review_id FROM workspace_code_reviews WHERE id=101", Long.class))
          .isEqualTo(77);
      for (int reviewId : List.of(101, 102, 103, 104, 110)) {
        assertThat(
                jdbc.queryForObject(
                    "SELECT additions FROM workspace_code_reviews WHERE id=?",
                    Integer.class,
                    reviewId))
            .isEqualTo(
                jdbc.queryForObject(
                    "SELECT SUM(additions) FROM workspace_code_review_files WHERE review_id=?",
                    Integer.class,
                    reviewId));
        assertThat(
                jdbc.queryForObject(
                    "SELECT deletions FROM workspace_code_reviews WHERE id=?",
                    Integer.class,
                    reviewId))
            .isEqualTo(
                jdbc.queryForObject(
                    "SELECT SUM(deletions) FROM workspace_code_review_files WHERE review_id=?",
                    Integer.class,
                    reviewId));
      }
    }
  }
}
