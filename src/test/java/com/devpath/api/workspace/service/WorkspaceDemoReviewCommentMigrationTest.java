package com.devpath.api.workspace.service;

import static org.assertj.core.api.Assertions.assertThat;

import java.nio.charset.StandardCharsets;
import java.sql.DriverManager;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.springframework.core.io.ClassPathResource;
import org.springframework.core.io.support.EncodedResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

class WorkspaceDemoReviewCommentMigrationTest {

  @ParameterizedTest
  @ValueSource(strings = {"postgresql", "oracle"})
  void fillsOnlyMissingInvitedMemberCommentsAndPreservesExistingOrDeletedComments(String vendor)
      throws Exception {
    try (var connection = DriverManager.getConnection("jdbc:h2:mem:demo_comments_" + vendor)) {
      var jdbc = new JdbcTemplate(new SingleConnectionDataSource(connection, true));
      String booleanType = vendor.equals("oracle") ? "INTEGER" : "BOOLEAN";
      String active = vendor.equals("oracle") ? "0" : "FALSE";
      String deleted = vendor.equals("oracle") ? "1" : "TRUE";
      jdbc.execute("CREATE TABLE users (user_id BIGINT, email VARCHAR(200))");
      jdbc.execute(
          "CREATE TABLE workspace (id BIGINT, owner_id BIGINT, type VARCHAR(20), is_deleted "
              + booleanType
              + ")");
      jdbc.execute("CREATE TABLE workspace_member (workspace_id BIGINT, learner_id BIGINT)");
      jdbc.execute(
          "CREATE TABLE workspace_code_reviews (id BIGINT, workspace_id BIGINT, file_path VARCHAR(500), external_provider VARCHAR(50), external_id VARCHAR(220), is_deleted "
              + booleanType
              + ")");
      jdbc.execute(
          "CREATE TABLE workspace_code_review_comments (id BIGINT GENERATED BY DEFAULT AS IDENTITY, review_id BIGINT, workspace_id BIGINT, author_id BIGINT, file_path VARCHAR(500), body VARCHAR(4000), status_label VARCHAR(50), is_deleted "
              + booleanType
              + ", created_at TIMESTAMP, updated_at TIMESTAMP)");
      jdbc.execute(
          "INSERT INTO users VALUES (101, 'kim.hakseup@devpath.com'), (102, 'park.juseung@devpath.com'), (103, 'kim.taehyung@devpath.com'), (104, 'other@devpath.com')");
      jdbc.execute(
          "INSERT INTO workspace VALUES (11,101,'SQUAD',"
              + active
              + "), (12,104,'SQUAD',"
              + active
              + "), (13,101,'SQUAD',"
              + active
              + "), (14,101,'SQUAD',"
              + active
              + "), (15,101,'SQUAD',"
              + deleted
              + ")");
      jdbc.execute(
          "INSERT INTO workspace_member VALUES (11,102),(11,103),(12,102),(12,103),(13,102),(13,103),(14,102),(15,102),(15,103)");
      jdbc.execute(
          "INSERT INTO workspace_code_reviews VALUES (21,11,'DailyRecordService.java','DEMO','routinecare-records-v1#1',"
              + active
              + "), (22,12,'other.java','DEMO','routinecare-records-v1#1',"
              + active
              + "), (23,13,'manual.java','GITHUB','routinecare-records-v1#1',"
              + active
              + "), (24,14,'existing.java','DEMO','routinecare-records-v1#1',"
              + active
              + "), (25,15,'deleted.java','DEMO','routinecare-records-v1#1',"
              + active
              + ")");
      jdbc.execute(
          "INSERT INTO workspace_code_review_comments (review_id, workspace_id, author_id, body, is_deleted) VALUES (21,11,102,'직접 작성한 댓글',"
              + active
              + "), (24,14,102,'삭제한 댓글',"
              + deleted
              + ")");
      var resource =
          new EncodedResource(
              new ClassPathResource(
                  "db/migration/" + vendor + "/V3__seed_routinecare_review_member_comments.sql"),
              StandardCharsets.UTF_8);
      ScriptUtils.executeSqlScript(connection, resource);
      ScriptUtils.executeSqlScript(connection, resource);

      assertThat(
              jdbc.queryForObject(
                  "SELECT count(*) FROM workspace_code_review_comments", Integer.class))
          .isEqualTo(3);
      assertThat(
              jdbc.queryForObject(
                  "SELECT body FROM workspace_code_review_comments WHERE author_id=103",
                  String.class))
          .isEqualTo(WorkspaceDemoScenario.TAEHYUNG_COMMENT);
      assertThat(
              jdbc.queryForObject(
                  "SELECT file_path FROM workspace_code_review_comments WHERE author_id=103",
                  String.class))
          .isEqualTo("DailyRecordService.java");
      assertThat(
              jdbc.queryForList(
                  "SELECT body FROM workspace_code_review_comments WHERE author_id=102",
                  String.class))
          .containsExactlyInAnyOrder("직접 작성한 댓글", "삭제한 댓글");
    }
  }
}
