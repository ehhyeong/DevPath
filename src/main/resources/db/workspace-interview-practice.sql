CREATE TABLE IF NOT EXISTS workspace_interview_practice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    content TEXT NOT NULL,
    shared_answers TEXT,
    CONSTRAINT uq_workspace_interview_practice UNIQUE (workspace_id, user_id)
);

ALTER TABLE workspace_interview_practice ADD COLUMN IF NOT EXISTS shared_answers TEXT;

DO $$
DECLARE
    constraint_name text;
BEGIN
    FOR constraint_name IN
        SELECT conname FROM pg_constraint
         WHERE conrelid = 'workspace_doc'::regclass AND contype = 'c'
           AND pg_get_constraintdef(oid) LIKE '%doc_type%'
    LOOP
        EXECUTE format('ALTER TABLE workspace_doc DROP CONSTRAINT %I', constraint_name);
    END LOOP;
    ALTER TABLE workspace_doc ADD CONSTRAINT workspace_doc_doc_type_check
        CHECK (doc_type IN ('ERD', 'API_SPEC', 'INFRA', 'MEETING_SETTINGS', 'INTERVIEW_QUESTIONS'));
END $$;
